def _write_csv(path: Path, header: list[str], rows: list[list[object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)
    print(f"wrote {path}  ({len(rows)} rows)")


def main() -> None:
    party_rows = [
        [pid, std_name, ideology]
        for pid, (std_name, ideology) in sorted(_IDEOLOGY.items())
    ]
    _write_csv(
        SEEDS_DIR / "party_metadata.csv",
        ["party_id", "standardised_name", "ideology_he"],
        party_rows,
    )

    committee_rows = [
        [cid, K25, ministry, _MINISTRY_NOTE]
        for cid, ministries in sorted(_COMMITTEE_MINISTRIES.items())
        for ministry in ministries
    ]
    _write_csv(
        SEEDS_DIR / "committee_topics_ministries.csv",
        ["committee_id", "knesset_num", "ministry_he", "notes_he"],
        committee_rows,
    )


if __name__ == "__main__":
    main()
